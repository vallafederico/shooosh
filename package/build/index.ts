import { minifyShader } from "./minify"
export { minifyShader } from "./minify"
/** Node/Bun build tools. .wgsl imports produce plain shader data, never a compiler import. */
import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"
import { compileShader } from "../compiler/index"
export { compileShader } from "../compiler/index"
export type ShaderBuildOptions = { backend?: "both" | "webgl2" | "webgpu"; minify?: boolean }
export function shaderModule(source: string, options: ShaderBuildOptions = {}): string {
  const backend = options.backend ?? "both"
  if (!["both", "webgl2", "webgpu"].includes(backend)) throw new Error(`Unknown backend: ${backend}`)
  if (!/\bfn\s+fsMain\s*\(/.test(source)) throw new Error("Expected a WGSL fsMain fragment")
  // GPU-only authoring need not fit the GLSL translator's subset.
  const shader = backend === "webgpu" ? { fragment: source } : compileShader(source)
  const artifact = backend === "webgl2" ? { fragmentGlsl: (shader as ReturnType<typeof compileShader>).fragmentGlsl } : shader
  if (options.minify) for (const key of Object.keys(artifact)) (artifact as Record<string,string>)[key] = minifyShader((artifact as Record<string,string>)[key]!)
  return `// Generated by shooosh. Do not edit.\n${Object.entries(artifact).map(([key,value]) => `export const ${key} = ${JSON.stringify(value)};`).join("\n")}\nexport default { ${Object.keys(artifact).join(", ")} };\n`
}
/** Vite/Rollup compatible plugin. Other query suffixes (?raw, ?url) pass through. */
export function shoooshShaders(options: ShaderBuildOptions = {}) {
  if (!["both", "webgl2", "webgpu"].includes(options.backend ?? "both")) throw new Error("Invalid shader backend")
  let production = false
  return {
    configResolved(config: { command: string }) { production = config.command === "build" },
    name: "shooosh-shaders",
    enforce: "pre" as const,
    async resolveId(this: { resolve: (id: string, importer?: string, options?: { skipSelf: boolean }) => Promise<unknown> }, id: string, importer?: string): Promise<any> {
      const backend = options.backend ?? "both"
      if (backend === "both") return null
      if (/^shooosh\/(webgl2|webgpu)(?:\/dom)?$/.test(id) && !id.startsWith(`shooosh/${backend}`)) {
        throw new Error(`Import ${id} conflicts with backend ${backend}.`)
      }
      if (id === "shooosh" || id === "shooosh/dom") {
        return this.resolve(`shooosh/${backend}${id.endsWith("/dom") ? "/dom" : ""}`, importer, { skipSelf: true })
      }
      return null
    },
    transform(source: string, id: string) {
      if (!id.endsWith(".wgsl")) return null
      try { return { code: shaderModule(source, { ...options, minify: options.minify ?? production }), map: null } }
      catch (error) { throw new Error(`${id}: ${error instanceof Error ? error.message : error}`) }
    },
  }
}
/** CLI: shooosh-shader input.wgsl output.mjs; validation completes before writing. */
export async function runShaderCli(args: string[]): Promise<number> {
  const minify = args.includes("--minify")
  args = args.filter(arg => arg !== "--minify")
  const backend = args.find(arg => arg.startsWith("--backend="))?.slice(10) ?? "both"
  args = args.filter(arg => !arg.startsWith("--backend="))
  if (args.length !== 2 || args.some(arg => arg.startsWith("-")) || !["both", "webgl2", "webgpu"].includes(backend)) {
    console.error("Usage: shooosh-shader input.wgsl output.mjs [--backend=both|webgl2|webgpu] [--minify]")
    return 1
  }
  const [input, output] = args.map(arg => resolve(arg))
  if (!/\.(mjs|js|ts)$/.test(output!)) { console.error("Output must end in .mjs, .js or .ts"); return 1 }
  if (input === output) { console.error("Input and output must differ"); return 1 }
  try {
    const module = shaderModule(await readFile(input!, "utf8"), { backend: backend as ShaderBuildOptions["backend"], minify })
    await writeFile(output!, module)
    await writeFile(output!.replace(/\.(mjs|js|ts)$/, (_, ext) => ext === "mjs" ? ".d.mts" : ".d.ts"), `${backend !== 'webgl2' ? 'export declare const fragment: string;\n' : ''}${backend !== 'webgpu' ? 'export declare const fragmentGlsl: string;\n' : ''}declare const shader: Readonly<{ ${backend !== 'webgl2' ? 'fragment: string;' : ''} ${backend !== 'webgpu' ? 'fragmentGlsl: string;' : ''} }>;\nexport default shader;\n`)
    return 0
  } catch (error) { console.error(`${input}: ${error instanceof Error ? error.message : error}`); return 1 }
}

/** Bun build plugin for the same standalone shader modules (no runtime compiler). */
export function shoooshBunShaders(options: ShaderBuildOptions = {}) {
  return { name: "shooosh-shaders", setup(builder: {
    onLoad(options: { filter: RegExp }, callback: (args: { path: string }) => Promise<{ contents: string; loader: "js" }>): void
  }) {
    builder.onLoad({ filter: /\.wgsl$/ }, async ({path}) => ({ contents: shaderModule(await readFile(path,"utf8"), { ...options, minify: options.minify ?? true }), loader: "js" }))
  } }
}
